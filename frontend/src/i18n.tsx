type I18nValue = {
  lang: LocaleCode;
  dir: "rtl" | "ltr";
  t: (key: string) => string;
  to: (path: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function isLocale(value: string | undefined): value is LocaleCode {
  return LOCALES.some((item) => item.code === value);
}

export function localeFromPath(pathname: string): LocaleCode {
  const code = pathname.split("/")[1];
  return isLocale(code) ? code : "fa";
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const location = useLocation();
  const lang = localeFromPath(location.pathname);
  const dir = LOCALES.find((item) => item.code === lang)?.dir || "rtl";
  setApiLang(lang);

  useEffect(() => {
    document.documentElement.lang = lang === "fa-AF" ? "fa-AF" : lang;
    document.documentElement.dir = dir;
    localStorage.setItem("lang", lang);
  }, [lang, dir]);

  const value: I18nValue = {
    lang,
    dir,
    t: (key) => TEXT[lang][key] || TEXT.fa[key] || key,
    to: (path) => {
      if (!path.startsWith("/") || path.startsWith("/admin")) return path;
      const [pathname, search = ""] = path.split("?");
      const suffix = pathname === "/" ? "" : pathname;
      return `/${lang}${suffix}${search ? `?${search}` : ""}`;
    },
  };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n outside provider");
  }
  return value;
}

export function useSwitchLang() {
  const navigate = useNavigate();
  const location = useLocation();
  return (code: LocaleCode) => {
    const parts = location.pathname.split("/");
    parts[1] = code;
    const next = parts.join("/") || `/${code}`;
    navigate(`${next}${location.search}`);
  };
}
