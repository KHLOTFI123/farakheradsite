def request(method: str, url: str, data: bytes | None = None, headers: dict | None = None) -> bytes:
    req = urllib.request.Request(url, data=data, method=method, headers=headers or {})
    try:
        with urllib.request.urlopen(req, timeout=60) as res:
            return res.read()
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"{method} {url} -> {exc.code}: {detail}") from exc


def download_images() -> None:
    ua = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
        "Accept": "image/avif,image/webp,image/apng,image/*,*/*;q=0.8",
    }
    for name, url in IMAGES.items():
        dest = OUT / name
        if dest.exists() and dest.stat().st_size > 10000:
            print(f"skip image {name}")
            continue
        print(f"download {name}")
        try:
            req = urllib.request.Request(url, headers=ua)
            with urllib.request.urlopen(req, timeout=60) as res:
                dest.write_bytes(res.read())
        except urllib.error.HTTPError:
            fallback = f"https://picsum.photos/seed/{name}/1600/900"
            print(f"fallback {name}")
            req = urllib.request.Request(fallback, headers=ua)
            with urllib.request.urlopen(req, timeout=60) as res:
                dest.write_bytes(res.read())


def login() -> str:
    payload = json.dumps({"username": "admin", "password": "admin123"}).encode()
    raw = request(
        "POST",
        f"{BASE}/api/auth/login",
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    return json.loads(raw)["access_token"]


def upload(token: str, path: Path) -> str:
    boundary = "----FarakheradBoundary7MA4YWxkTrZu0gW"
    data = (
        f"--{boundary}\r\n"
        f'Content-Disposition: form-data; name="file"; filename="{path.name}"\r\n'
        "Content-Type: image/jpeg\r\n\r\n"
    ).encode() + path.read_bytes() + f"\r\n--{boundary}--\r\n".encode()
    raw = request(
        "POST",
        f"{BASE}/api/admin/upload",
        data=data,
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": f"multipart/form-data; boundary={boundary}",
        },
    )
    return json.loads(raw)["url"]


def existing_slugs() -> set[str]:
    raw = request("GET", f"{BASE}/api/articles")
    return {item["slug"] for item in json.loads(raw)}


def main() -> int:
    download_images()
    token = login()
    have = existing_slugs()
    created = 0
    for item in ARTICLES:
        if item["slug"] in have:
            print(f"skip article {item['slug']}")
            continue
        image_url = upload(token, OUT / item["image"])
        body = json.dumps(
            {
                "title": item["title"],
                "slug": item["slug"],
                "excerpt": item["excerpt"],
                "content": item["content"].strip(),
                "image_url": image_url,
            },
            ensure_ascii=False,
        ).encode("utf-8")
        request(
            "POST",
            f"{BASE}/api/admin/articles",
            data=body,
            headers={
                "Authorization": f"Bearer {token}",
                "Content-Type": "application/json",
            },
        )
        created += 1
        print(f"created {item['slug']}")
    print(f"done created={created}")
    return 0


